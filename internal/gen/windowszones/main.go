// Command windowszones regenerates ../../../windowszones.go from CLDR.
//
// Windows does not name its timezones the way the rest of the world does: the
// registry holds "Tokyo Standard Time", not "Asia/Tokyo". The mapping between
// the two is maintained by CLDR, in common/supplemental/windowsZones.xml, and
// there is no way to derive it — it has to be carried.
//
// Only the territory="001" rows are taken. CLDR lists a mapping per territory
// because one Windows zone can cover several IANA zones (Central Europe covers
// Warsaw, Budapest, Prague and more); territory="001" is the "world" default,
// which is the canonical IANA zone for that Windows zone and the only sensible
// answer when all we have is the Windows name.
//
// Run it with:
//
//	go run ./internal/gen/windowszones
//
// It fetches the current CLDR data, so the output moves when CLDR does. Check
// the diff before committing.
package main

import (
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

const (
	source = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml"
	out    = "windowszones.go"
)

// One row of the world-default mapping. The attributes are in a fixed order in
// the CLDR file, which a regexp is enough for — pulling in an XML decoder to
// read three attributes would be the heavier choice, not the safer one, because
// the shape is verified below.
var row = regexp.MustCompile(`<mapZone other="([^"]+)" territory="001" type="([^"]+)"/>`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "windowszones:", err)
		os.Exit(1)
	}
}

func run() error {
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(source)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: %s", source, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}

	pairs := map[string]string{}
	for _, m := range row.FindAllStringSubmatch(string(body), -1) {
		win, iana := m[1], m[2]
		if strings.ContainsAny(iana, " \t") {
			return fmt.Errorf("%q maps to several zones (%q); the world default is supposed to be one", win, iana)
		}
		if prev, dup := pairs[win]; dup {
			return fmt.Errorf("%q appears twice (%q and %q)", win, prev, iana)
		}
		pairs[win] = iana
	}
	// A sanity floor rather than an exact count, which would need editing every
	// time CLDR adds a zone. A parse that quietly matched nothing is the failure
	// this catches.
	if len(pairs) < 100 {
		return fmt.Errorf("only %d mappings parsed; the file's shape has probably changed", len(pairs))
	}

	names := make([]string, 0, len(pairs))
	for win := range pairs {
		names = append(names, win)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "// %d mappings, from %s\nvar windowsZones = map[string]string{\n", len(pairs), source)
	for _, win := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", win, pairs[win])
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

